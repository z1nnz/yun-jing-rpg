// node tools/qingxi-waterworks-b/tests/make-golden.mjs
// Writes tests/golden.json (JS core answers for every scenario step) and the site tables the Unity port loads.
import { writeFileSync, mkdirSync } from 'node:fs';
import { SCENARIOS, replay } from './replay.mjs';
import { siteTables } from '../src/tables.mjs';

export const golden = () => ({ _note: 'Generated by make-golden.mjs from the JS core. Do not edit by hand.',
  scenarios: Object.fromEntries(SCENARIOS.map(sc => [sc.id, replay(sc)])) });
export const SITE_JSON = new URL('../unity/Assets/Resources/waterworks-site.json', import.meta.url);
export const GOLDEN_JSON = new URL('./golden.json', import.meta.url);

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll('\\', '/').split('/').pop())) {
  writeFileSync(GOLDEN_JSON, JSON.stringify(golden(), null, 1) + '\n');
  mkdirSync(new URL('.', SITE_JSON), { recursive: true });
  writeFileSync(SITE_JSON, JSON.stringify(siteTables(), null, 1) + '\n');
  console.log('wrote golden.json and unity/Assets/Resources/waterworks-site.json');
}
